-- AJUDA: pedidos de ajuda / problemas / apoio técnico enviados de dentro do app (página Ajuda)
-- e vistos por quem administra a plataforma em /admin.
--
-- Só ADITIVO: cria uma tabela nova e 3 funções; não altera nem apaga nada que exista.
-- PRÉ-REQUISITOS: `multi_empresa.sql` e `multi_empresa_admin.sql` já aplicados (já estão na L & A).
-- Seguro rodar mais de uma vez. Corre ANTES de publicar a versão do app que usa isto.
--
-- COMO FUNCIONA
--   * `help_reports`: nunca se lê/escreve direto pela API (RLS ligado, sem permissões).
--   * `submit_help_report(...)`: qualquer conta com empresa (gerência, supervisor, funcionário) envia
--     um pedido; a empresa e o e-mail de quem envia vêm do login (não do que o app diz). Máx. 20/dia por pessoa.
--   * `admin_list_help_reports` / `admin_set_help_report_status`: só a conta de administração.

create table if not exists public.help_reports (
  id bigint generated by default as identity primary key,
  company_id integer not null references public.companies (id) on delete cascade,
  created_at timestamptz not null default now(),
  kind text not null default 'problem' check (kind in ('problem', 'support', 'idea')),
  message text not null check (char_length(btrim(message)) between 3 and 4000),
  screen text,          -- ecrã onde a pessoa estava (ex.: "horas")
  role text check (role is null or role in ('manager', 'supervisor', 'employee')),
  lang text,
  author_name text,
  author_email text,
  device text,          -- navegador/aparelho (para reproduzir o erro)
  status text not null default 'new' check (status in ('new', 'seen', 'done')),
  handled_at timestamptz
);
create index if not exists help_reports_status_created_idx on public.help_reports (status, created_at desc);
create index if not exists help_reports_company_idx on public.help_reports (company_id);

alter table public.help_reports enable row level security;
revoke all on public.help_reports from anon, authenticated;

-- Enviar um pedido (de dentro do app).
create or replace function public.submit_help_report(
  p_kind text,
  p_message text,
  p_screen text default null,
  p_role text default null,
  p_lang text default null,
  p_author_name text default null,
  p_device text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  cid integer;
  mail text;
  msg text := btrim(coalesce(p_message, ''));
  n integer;
  new_id bigint;
begin
  if auth.role() is distinct from 'authenticated' then
    raise exception 'não autenticado' using errcode = '42501';
  end if;
  cid := private.my_company_id();
  if cid is null then
    raise exception 'sem empresa associada' using errcode = '42501';
  end if;
  if p_kind is null or p_kind not in ('problem', 'support', 'idea') then
    raise exception 'invalid_kind';
  end if;
  if char_length(msg) < 3 then
    raise exception 'invalid_message';
  end if;
  mail := nullif(private.auth_email(), '');
  select count(*) into n from public.help_reports h
   where h.company_id = cid and h.author_email is not distinct from mail and h.created_at > now() - interval '1 day';
  if n >= 20 then
    raise exception 'too_many';
  end if;
  insert into public.help_reports (company_id, kind, message, screen, role, lang, author_name, author_email, device)
  values (
    cid, p_kind, left(msg, 4000), left(nullif(btrim(coalesce(p_screen, '')), ''), 60),
    case when p_role in ('manager', 'supervisor', 'employee') then p_role else null end,
    left(nullif(btrim(coalesce(p_lang, '')), ''), 8),
    left(nullif(btrim(coalesce(p_author_name, '')), ''), 120), mail,
    left(nullif(btrim(coalesce(p_device, '')), ''), 200)
  )
  returning id into new_id;
  return new_id;
end;
$$;

-- /admin: lista de pedidos (os novos primeiro).
create or replace function public.admin_list_help_reports(p_status text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform private.admin_guard();
  return coalesce((
    select jsonb_agg(x.j order by x.is_new desc, x.created_at desc)
      from (
        select h.created_at, (h.status = 'new') as is_new, jsonb_build_object(
          'id', h.id, 'createdAt', h.created_at, 'kind', h.kind, 'message', h.message, 'screen', h.screen,
          'role', h.role, 'lang', h.lang, 'authorName', h.author_name, 'authorEmail', h.author_email,
          'device', h.device, 'status', h.status, 'handledAt', h.handled_at,
          'companyId', c.id, 'companyName', c.name, 'companyCode', c.code
        ) as j
          from public.help_reports h
          join public.companies c on c.id = h.company_id
         where p_status is null or h.status = p_status
         order by (h.status = 'new') desc, h.created_at desc
         limit 300
      ) x
  ), '[]'::jsonb);
end;
$$;

-- /admin: marcar como visto / resolvido (ou voltar a novo).
create or replace function public.admin_set_help_report_status(p_id bigint, p_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.admin_guard();
  if p_status is null or p_status not in ('new', 'seen', 'done') then
    raise exception 'invalid_status';
  end if;
  update public.help_reports
     set status = p_status, handled_at = case when p_status = 'new' then null else now() end
   where id = p_id;
end;
$$;

revoke all on function public.submit_help_report(text, text, text, text, text, text, text) from public, anon;
revoke all on function public.admin_list_help_reports(text) from public, anon;
revoke all on function public.admin_set_help_report_status(bigint, text) from public, anon;
grant execute on function public.submit_help_report(text, text, text, text, text, text, text) to authenticated, service_role;
grant execute on function public.admin_list_help_reports(text) to authenticated, service_role;
grant execute on function public.admin_set_help_report_status(bigint, text) to authenticated, service_role;

