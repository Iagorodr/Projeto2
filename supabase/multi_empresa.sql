-- Estado da assinatura: none | suspended | active | grace | expired.
-- A data conta até ao fim do dia (no fuso da empresa); depois, 7 dias de tolerância.
create or replace function private.company_state(cid integer)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when c.id is null then 'none'
    when c.suspended then 'suspended'
    when c.valid_until is null then 'active'
    when (now() at time zone c.timezone)::date <= c.valid_until then 'active'
    when (now() at time zone c.timezone)::date <= c.valid_until + 7 then 'grace'
    else 'expired'
  end
  from (select cid as id) q
  left join public.companies c on c.id = q.id;
$$;

-- Empresa de quem está logado (pelo email da sessão): funcionário/gerência em
-- `staff`, ou a conta da empresa em `company_settings`.
create or replace function private.my_company_id()
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select s.company_id from public.staff s
      where private.auth_email() <> '' and lower(btrim(s.email)) = private.auth_email()
      order by s.id limit 1),
    (select cs.id from public.company_settings cs
      where private.auth_email() <> '' and lower(btrim(cs.email)) = private.auth_email()
      order by cs.id limit 1)
  );
$$;

-- A assinatura da empresa de quem está logado permite usar o app?
create or replace function private.company_ok()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select private.company_state(private.my_company_id()) in ('active', 'grace');
$$;

-- Gatilho (insert): a linha fica SEMPRE na empresa de quem grava, seja qual for
-- o company_id enviado. Chamadas de confiança (service_role / SQL Editor) mandam.
create or replace function private.set_company_id()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  cid integer;
begin
  if private.is_privileged() then
    return new;
  end if;
  cid := private.my_company_id();
  if cid is null then
    raise exception 'sem empresa associada a esta conta' using errcode = '42501';
  end if;
  new.company_id := cid;
  return new;
end;
$$;

-- Gatilho (update): ninguém muda uma linha de empresa.
create or replace function private.keep_company_id()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.company_id is distinct from old.company_id and not private.is_privileged() then
    new.company_id := old.company_id;
  end if;
  return new;
end;
$$;

-- Gatilho: um email só pode existir uma vez no banco inteiro (staff + conta da
-- empresa), mesmo entre empresas. A mensagem não revela de quem é.
create or replace function private.check_email_unique()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  e text := lower(btrim(coalesce(new.email, '')));
begin
  if e = '' then
    return new;
  end if;
  if tg_op = 'UPDATE' and e = lower(btrim(coalesce(old.email, ''))) then
    return new;
  end if;
  if exists (select 1 from public.staff s
              where lower(btrim(s.email)) = e
                and not (tg_table_name = 'staff' and s.id = new.id))
     or exists (select 1 from public.company_settings c
                 where lower(btrim(c.email)) = e
                   and not (tg_table_name = 'company_settings' and c.id = new.id)) then
    raise exception 'Este e-mail não está disponível.' using errcode = '23505';
  end if;
  return new;
end;
$$;

