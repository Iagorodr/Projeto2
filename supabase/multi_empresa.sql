-- ─────────────────────────────────────────────────────────────────────────
-- 5. Políticas de RLS: só a própria empresa, e só com a assinatura em dia
--    (ler = qualquer conta da empresa; escrever = gerência da empresa)
-- ─────────────────────────────────────────────────────────────────────────
do $$
declare
  tbl text;
  col text;
begin
  foreach tbl in array array['clients', 'staff', 'company_settings', 'app_data'] loop
    col := case when tbl in ('company_settings', 'app_data') then 'id' else 'company_id' end;
    execute format('alter table public.%I enable row level security', tbl);
    execute format('drop policy if exists authenticated_full_access on public.%I', tbl);
    execute format('drop policy if exists %I on public.%I', tbl || '_select', tbl);
    execute format('drop policy if exists %I on public.%I', tbl || '_insert_manager', tbl);
    execute format('drop policy if exists %I on public.%I', tbl || '_update_manager', tbl);
    execute format('drop policy if exists %I on public.%I', tbl || '_delete_manager', tbl);
    execute format(
      'create policy %I on public.%I for select to authenticated using (%I = (select private.my_company_id()) and (select private.company_ok()))',
      tbl || '_select', tbl, col);
    execute format(
      'create policy %I on public.%I for insert to authenticated with check (%I = (select private.my_company_id()) and (select private.company_ok()) and (select private.is_manager()))',
      tbl || '_insert_manager', tbl, col);
    execute format(
      'create policy %I on public.%I for update to authenticated using (%I = (select private.my_company_id()) and (select private.company_ok()) and (select private.is_manager())) with check (%I = (select private.my_company_id()) and (select private.company_ok()) and (select private.is_manager()))',
      tbl || '_update_manager', tbl, col, col);
    execute format(
      'create policy %I on public.%I for delete to authenticated using (%I = (select private.my_company_id()) and (select private.company_ok()) and (select private.is_manager()))',
      tbl || '_delete_manager', tbl, col);
  end loop;
end $$;

