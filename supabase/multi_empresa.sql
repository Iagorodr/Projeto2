--   * `company_id` em clients, staff e push_subscriptions. Em company_settings
--     e app_data o próprio `id` passa a ser o id da empresa (a empresa 1 mantém
--     id = 1, por isso a versão antiga do app continua a funcionar).
--   * Cada pessoa só vê/mexe nos dados da SUA empresa (política por linha), e só
