-- Antes do login (anónimo): só diz se o código existe. Nada mais é revelado.
create or replace function public.company_lookup(p_code text)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object('found', exists (
    select 1 from public.companies c
    where lower(c.code) = lower(btrim(coalesce(p_code, '')))
  ));
$$;

-- Depois do login (qualquer conta, mesmo com a assinatura vencida): estado e
-- datas da empresa de quem chama. `daysLeft` = dias até ao fim da validade
-- (negativo depois); `graceDaysLeft` = dias que ainda restam de tolerância,
-- contando o de hoje (null fora da tolerância).
create or replace function public.my_company_status()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  cid integer;
  c public.companies;
  st text;
  today date;
begin
  if auth.role() is distinct from 'authenticated' and not private.is_privileged() then
    raise exception 'não autenticado' using errcode = '42501';
  end if;
  cid := private.my_company_id();
  if cid is null then
    return jsonb_build_object('state', 'none');
  end if;
  select * into c from public.companies where id = cid;
  st := private.company_state(cid);
  today := (now() at time zone c.timezone)::date;
  return jsonb_build_object(
    'state', st,
    'companyId', c.id,
    'code', c.code,
    'name', c.name,
    'validUntil', c.valid_until,
    'daysLeft', case when c.valid_until is null then null else c.valid_until - today end,
    'graceDaysLeft', case when st = 'grace' then c.valid_until + 7 - today + 1 else null end
  );
end;
$$;

revoke all on function public.company_lookup(text) from public;
revoke all on function public.my_company_status() from public, anon;
grant execute on function public.company_lookup(text) to anon, authenticated, service_role;
grant execute on function public.my_company_status() to authenticated, service_role;

