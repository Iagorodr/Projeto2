create or replace function public.patch_horas_data(patch jsonb, p_company integer default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  cid integer;
  me bigint;
  cur jsonb;
  clean jsonb := '{}'::jsonb;
  k text;
  v jsonb;
  old jsonb;
  nv jsonb;
begin
  if auth.role() is distinct from 'authenticated' and not private.is_privileged() then
    raise exception 'não autenticado' using errcode = '42501';
  end if;
  cid := case when private.is_privileged() then p_company else private.my_company_id() end;
  if cid is null then
    raise exception 'sem empresa associada' using errcode = '42501';
  end if;
  if not private.is_privileged() and private.company_state(cid) not in ('active', 'grace') then
    raise exception 'assinatura da empresa indisponível' using errcode = '42501';
  end if;
  patch := coalesce(patch, '{}'::jsonb);
  if jsonb_typeof(patch) <> 'object' then
    raise exception 'patch_horas_data: o patch tem de ser um objeto';
  end if;

  if private.is_manager() then
    update public.app_data
       set horas_data = coalesce(horas_data, '{}'::jsonb) || patch
     where id = cid;
    return;
  end if;

  me := private.my_staff_id();
  if me is null then
    raise exception 'sem permissão para gravar horas' using errcode = '42501';
  end if;

  select coalesce(horas_data, '{}'::jsonb) into cur from public.app_data where id = cid for update;
  if cur is null then return; end if;

  for k, v in select key, value from jsonb_each(patch) loop
    if jsonb_typeof(v) <> 'object' then continue; end if;
    old := cur -> k;

    if k = me::text then
      nv := v - 'paid' - 'reopened';
      nv := nv || jsonb_build_object('paid', coalesce(old -> 'paid', 'false'::jsonb));
      if old ? 'reopened' then
        nv := nv || jsonb_build_object('reopened', old -> 'reopened');
      end if;
      nv := nv || jsonb_build_object(
        'entries', private.horas_clean_entries(coalesce(v -> 'entries', old -> 'entries', '[]'::jsonb), old -> 'entries'));
    elsif exists (select 1 from public.staff s where s.id::text = k and s.company_id = cid) then
      if old is null then
        nv := jsonb_build_object(
          'status', 'pendente', 'paid', false, 'lockedWeeks', '{}'::jsonb, 'noClientDays', '[]'::jsonb,
          'entries', private.horas_clean_entries(coalesce(v -> 'entries', '[]'::jsonb), '[]'::jsonb));
      else
        nv := old || jsonb_build_object(
          'entries', private.horas_clean_entries(coalesce(v -> 'entries', old -> 'entries', '[]'::jsonb), old -> 'entries'));
      end if;
    else
      continue;
    end if;
    clean := clean || jsonb_build_object(k, nv);
  end loop;

  update public.app_data
     set horas_data = coalesce(horas_data, '{}'::jsonb) || clean
   where id = cid;
end;
$$;

create or replace function public.patch_assignments(upserts jsonb, removed jsonb, p_company integer default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  cid integer;
begin
  if auth.role() is distinct from 'authenticated' and not private.is_privileged() then
    raise exception 'não autenticado' using errcode = '42501';
  end if;
  cid := case when private.is_privileged() then p_company else private.my_company_id() end;
  if cid is null then
    raise exception 'sem empresa associada' using errcode = '42501';
  end if;
  if not private.is_privileged() and private.company_state(cid) not in ('active', 'grace') then
