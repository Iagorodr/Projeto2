--     na empresa de quem chama. Têm um parâmetro extra `p_company`, que só é
--     usado por chamadas de confiança (service_role / SQL Editor).
--   * Validade: ativa → (valida até a data, inclusive) → tolerância de 7 dias
--     (tudo funciona; o app mostra avisos fortes) → vencida (tudo bloqueado).
--     `suspended` bloqueia de imediato. Os dados nunca são apagados.
--   * `company_lookup(código)` (anónimo): só diz se o código existe.
--   * `my_company_status()` (autenticado, funciona mesmo vencida): estado,
