// Rótulo legível do "assunto" de um Pedido (missingItems), qualquer que
// seja a língua ativa — usado pelos ecrãs de Avisos (gerência 4.7 /
// mobile+supervisor 5.6) e pelo cartão "Ocorrências do período" do
// Histórico (4.6). Etapa 4h corrige um bug que já existia: o "Assunto"
// escolhido pelo funcionário no formulário (Falta de produto/Problema no
// local/Outro) era descartado ao enviar — `kind` ficava sempre "produto"
// (ver `EmployeeAvisosScreen.jsx`), então nenhum ecrã sabia distinguir os 3
// assuntos de verdade. Agora `kind` guarda a CHAVE do assunto (nunca o
// texto já traduzido, mesma regra de sempre: guardar chaves estáveis,
// traduzir só ao exibir), e esta função decide o rótulo certo a cada
// chamada, incluindo para dados antigos (kind sempre "produto" antes desta
// correção — ainda caem aqui certo, "produto" continua uma chave válida).
function missingItemSubjectLabel(item, lang) {
  const t = T[lang] || T.pt;
  if (item.kind === "correcao") return t.avisos.correctionOfHours;
  const found = t.employeeAvisos.subjects.find((s) => s.key === item.kind);
  return found ? found.label : t.historico.missingProduct;
}

export { missingItemSubjectLabel };

